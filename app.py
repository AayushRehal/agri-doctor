"""
app.py
======
Agri Doctor — Agentic AI Crop Disease Diagnosis System
IBM watsonx.ai + IBM Granite Vision + Streamlit

Entry point. Run with:
    streamlit run app.py

Tabs:
  1. 🏠 Diagnosis        — image upload and Pathologist Agent output
  2. 💡 Recommendations  — Extension Officer Agent output + report download
  3. 📊 Evaluation       — LLM Evaluation Dashboard
  4. ℹ️  About            — application description and disclaimer
"""

import sys
import os

# ── Universal sys.path setup — works locally AND on Streamlit Cloud ───────────
# Local layout:  AgriDoctor/agents/, AgriDoctor/guardrails/, AgriDoctor/ui/ …
# Cloud layout:  all files flat at repo root (no subfolders)
#
# Strategy: add _HERE (app.py's directory) PLUS every known subdirectory.
# When running locally _HERE = AgriDoctor/, subdirs are AgriDoctor/agents/ etc.
# When running on Cloud _HERE = /mount/src/agri-doctor/, subdirs don't exist
# but all .py files are already at root so _HERE alone is enough.
_HERE = os.path.dirname(os.path.abspath(__file__))
for _sub in ("", "agents", "guardrails", "utils", "ui", "evaluation"):
    _p = os.path.join(_HERE, _sub) if _sub else _HERE
    if os.path.isdir(_p) and _p not in sys.path:
        sys.path.insert(0, _p)

import streamlit as st
from ui.styles import GLOBAL_CSS
from ui import home_tab, recommendations_tab, evaluation_tab
from utils.watsonx_client import check_credentials

# ── Page configuration ────────────────────────────────────────────────────────
st.set_page_config(
    page_title="Agri Doctor",
    page_icon="🌿",
    layout="wide",
    initial_sidebar_state="collapsed",
)

# ── Apply global CSS theme ────────────────────────────────────────────────────
st.markdown(GLOBAL_CSS, unsafe_allow_html=True)


# ── About tab renderer (defined first so it can be referenced below) ──────────

def _render_about():
    """Render the About / Information tab."""
    st.markdown("### ℹ️ About Agri Doctor")
    st.markdown("---")

    col1, col2 = st.columns([2, 1], gap="large")

    with col1:
        st.markdown("""
**Agri Doctor** is an Agentic AI application designed to assist farmers and agricultural
extension officers in identifying crop diseases and generating safe treatment recommendations.

#### 🤖 Agent Architecture

| Agent | Role | Model |
|---|---|---|
| **Pathologist Agent** | Analyses crop images, identifies diseases, assesses severity | `WATSONX_VISION_MODEL` env var |
| **Extension Officer Agent** | Generates safe treatment and prevention recommendations | `WATSONX_MODEL_ID` env var |
| **Multi-Agent Orchestrator** | Sequences agents, manages guardrails, tracks metrics | — |

#### 🛡️ Guardrails

- **Input Guardrails** — Validate image type/size and farmer note content; block prompt injection
- **Output Guardrails** — Validate LLM response quality; detect refusals and uncertainty markers
- **Security Guardrails** — Sanitise user inputs; mask API credentials in all logged data

#### 📊 Evaluation Dashboard

The Evaluation tab provides real-time visibility into:
- Response latency per agent (ms)
- Token usage per call
- Error counts
- Guardrail intervention statistics

#### 🔧 Technical Stack

- **UI:** Streamlit 1.64
- **Vision LLM:** IBM watsonx.ai — model set via `WATSONX_VISION_MODEL` (e.g. `mistralai/mistral-small-3-1-24b-instruct-2503`)
- **Text LLM:** IBM watsonx.ai — model set via `WATSONX_MODEL_ID` (e.g. `ibm/granite-4-h-small`)
- **SDK:** `ibm-watsonx-ai`
- **Image processing:** Pillow
- **Charts:** Plotly

#### 📁 Project Structure

```
AgriDoctor/
├── app.py                    ← Entry point
├── agents/
│   ├── pathologist.py        ← Pathologist Agent
│   ├── extension_officer.py  ← Extension Officer Agent
│   └── orchestrator.py       ← Multi-Agent Orchestrator
├── guardrails/
│   ├── input_guardrails.py
│   ├── output_guardrails.py
│   └── security_guardrails.py
├── evaluation/
│   └── metrics_tracker.py
├── utils/
│   ├── watsonx_client.py     ← IBM watsonx.ai wrapper
│   ├── image_utils.py
│   └── report_generator.py
└── ui/
    ├── styles.py
    ├── home_tab.py
    ├── recommendations_tab.py
    └── evaluation_tab.py
```
        """)

    with col2:
        st.markdown("""
#### ⚠️ Disclaimer

This application is designed as an **AI-assisted decision support tool** only.

- Results are generated by an AI model and **may not be 100% accurate**.
- Always **verify recommendations** with a qualified agricultural extension officer or plant pathologist.
- **Do not apply chemical treatments** solely based on AI output.
- Registered chemical use must comply with **local agricultural regulations**.
        """)
        st.markdown("---")
        st.markdown("""
#### 🚀 Getting Started

1. Copy `.env.example` → `.env`
2. Add your IBM watsonx.ai credentials
3. Install dependencies:
   ```
   pip install -r requirements.txt
   ```
4. Run the app:
   ```
   streamlit run app.py
   ```
        """)

    st.markdown("---")
    st.caption(
        "Agri Doctor v1.0 · Built with IBM watsonx.ai & IBM Granite Vision · "
        "For educational and research use · "
        "Always consult a qualified agricultural professional for final decisions."
    )


# ── App header ────────────────────────────────────────────────────────────────
st.markdown(
    """
    <div class="agri-header">
        <h1>🌿 Agri Doctor</h1>
        <p>Agentic AI Crop Disease Diagnosis — Powered by IBM watsonx.ai &amp; IBM Granite Vision</p>
    </div>
    """,
    unsafe_allow_html=True,
)

# ── Credential check banner ───────────────────────────────────────────────────
creds_ok, creds_msg = check_credentials()
if not creds_ok:
    st.warning(
        f"⚠️ **IBM watsonx.ai credentials not configured.**  \n"
        f"{creds_msg}  \n"
        f"**Local:** Copy `.env.example` to `.env` in the `AgriDoctor/` folder and fill in your credentials.  \n"
        f"**Streamlit Cloud:** Add credentials in your app's Secrets settings.  \n"
        f"The UI will load but analysis will not run until credentials are set."
    )

# ── Multi-tab layout ──────────────────────────────────────────────────────────
tab_diagnosis, tab_recommendations, tab_evaluation, tab_about = st.tabs([
    "🏠 Diagnosis",
    "💡 Recommendations",
    "📊 Evaluation",
    "ℹ️ About",
])

with tab_diagnosis:
    home_tab.render()

with tab_recommendations:
    recommendations_tab.render()

with tab_evaluation:
    evaluation_tab.render()

with tab_about:
    _render_about()
